# Create a list of book titles
book_titles = ["The Alchemist", "1984", "Moby Dick", "Pride and Prejudice"]

# Add two more books using append()
book_titles.append("To Kill a Mockingbird")
book_titles.append("The Great Gatsby")

# Remove one damaged book using remove()
book_titles.remove("Moby Dick")

# Sort the list alphabetically
book_titles.sort()

# Display the final list
print("Updated Book List:", book_titles)